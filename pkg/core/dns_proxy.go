const resolverMarker = "# Generated by Network Router"

// resolverDir is a variable so tests can redirect it away from the real system
// location.
var resolverDir = "/etc/resolver"

// DNSProxy answers queries for the tethered domains and feeds the resolved
// hosts to the RouteApplier.
//
// There is deliberately no domain matching here. macOS only forwards a query to
// this proxy when a file in /etc/resolver covers the name, and a resolver file
// covers the whole subtree beneath it. The resolver files are therefore the
// complete scope definition, and every query arriving here is in scope by
// construction. Re-checking the name against the configured list would be
// narrower than that scope: with `apple.com` configured, `www.apple.com` reaches
// this proxy and must be treated as in scope.
type DNSProxy struct {
	config    *Config
	upstream  *UpstreamResolver
	cache     *DNSCache
	applier   *RouteApplier

	mu        sync.Mutex
	running   bool
	servers   []*dns.Server
	resolvers []string
}

// NewDNSProxy creates a new DNS Proxy instance.
func NewDNSProxy(config *Config, upstream *UpstreamResolver, applier *RouteApplier) *DNSProxy {
	return &DNSProxy{
		config:   config,
		upstream: upstream,
		cache:    NewDNSCache(cacheDefaultMax),
		applier:  applier,
	}
}

// Start begins the DNS proxy server.
//
// Listeners are bound and confirmed serving before any resolver file is written.
// A resolver file names 127.0.0.1:<port> as the sole resolver for a whole domain
// subtree, so writing one while the port is unserved would stop those domains
// from resolving at all.
func (p *DNSProxy) Start() error {
	p.mu.Lock()
	defer p.mu.Unlock()

	if !p.config.DNSProxyEnabled || p.running {
		return nil
	}

	port := p.config.ProxyPort()
	address := fmt.Sprintf("127.0.0.1:%d", port)

	mux := dns.NewServeMux()
	mux.HandleFunc(".", p.handleDNSRequest)

	udpAddr, err := net.ResolveUDPAddr("udp", address)
	if err != nil {
		return fmt.Errorf("resolve %s: %w", address, err)
	}
	udpConn, err := net.ListenUDP("udp", udpAddr)
	if err != nil {
		return fmt.Errorf("bind udp %s: %w", address, err)
	}

	tcpAddr, err := net.ResolveTCPAddr("tcp", address)
	if err != nil {
		udpConn.Close()
		return fmt.Errorf("resolve %s: %w", address, err)
	}
	// A TCP listener is required: macOS retries over TCP when a reply is
	// truncated, and without a listener that retry is refused outright.
	tcpListener, err := net.ListenTCP("tcp", tcpAddr)
	if err != nil {
		udpConn.Close()
		return fmt.Errorf("bind tcp %s: %w", address, err)
	}

	servers := []*dns.Server{
		{PacketConn: udpConn, Handler: mux},
		{Listener: tcpListener, Handler: mux},
	}

	// Wait for each listener to report that it is serving. This makes a later
	// Shutdown well defined, and it is the check that guarantees resolver files
	// are only written once queries can actually be answered.
	started := make([]*dns.Server, 0, len(servers))
	for _, server := range servers {
		if err := activate(server); err != nil {
			for _, running := range started {
				_ = running.Shutdown()
			}
			udpConn.Close()
			tcpListener.Close()
			return fmt.Errorf("serve %s: %w", address, err)
		}
		started = append(started, server)
	}

	log.Printf("📡 DNS Proxy listening on %s (udp+tcp)", address)

	if err := p.setupSystemResolvers(port); err != nil {
		// Roll the listeners back so we never sit in the state where resolver
		// files point at a port this process is not serving.
		for _, server := range servers {
			_ = server.Shutdown()
		}
		return err
	}

	p.servers = servers
	p.running = true
	return nil
}

// Stop stops the DNS proxy server. Resolver files go first so the system falls
// back to its normal resolver as early as possible.
func (p *DNSProxy) Stop() error {
	p.mu.Lock()
	defer p.mu.Unlock()

	if !p.running {
		return nil
	}

	p.cleanupSystemResolvers()

	log.Println("🛑 Stopping DNS Proxy...")
	var firstErr error
	for _, server := range p.servers {
		if err := server.Shutdown(); err != nil && firstErr == nil {
			firstErr = err
		}
	}

	p.servers = nil
	p.running = false
	p.cache.Purge()
	return firstErr
}

// activate starts serving and blocks until the listener is live or fails.
func activate(server *dns.Server) error {
	ready := make(chan struct{})
	failed := make(chan error, 1)

	server.NotifyStartedFunc = func() { close(ready) }
	go func() {
		if err := server.ActivateAndServe(); err != nil {
			select {
			case failed <- err:
			default:
			}
		}
	}()

	select {
	case <-ready:
		return nil
	case err := <-failed:
		return err
	case <-time.After(2 * time.Second):
		return fmt.Errorf("listener did not start within 2s")
	}
}

// resolverFileNames derives the set of resolver files to create. The wildcard and
// bare forms of a domain name the same file, so the result is deduplicated to
// keep the created-file bookkeeping accurate.
func (p *DNSProxy) resolverFileNames() []string {
	unique := make(map[string]bool)

	for _, domain := range p.config.TetherDomains {
		name := strings.ToLower(strings.TrimSpace(domain))
		name = strings.TrimPrefix(name, "*.")
		name = strings.Trim(name, ".")
		if name == "" {
			continue
		}
		// A literal IP is not a DNS name; a resolver file named after one has no
		// effect. Such entries belong in tether_cidrs.
		if ip := net.ParseIP(name); ip != nil {
			log.Printf("⚠️ Ignoring literal IP %q in tether_domains; put it in tether_cidrs instead", name)
			continue
		}
		unique[name] = true
	}

	names := make([]string, 0, len(unique))
	for name := range unique {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}

// setupSystemResolvers creates resolver files for macOS.
func (p *DNSProxy) setupSystemResolvers(port int) error {
	if os.Geteuid() != 0 {
		// Without root the proxy still answers on the loopback port; it simply
		// receives nothing, which is harmless. Failing to start would be worse.
		log.Println("⚠️ Not running as root: skipping /etc/resolver setup, split DNS is inactive")
		return nil
	}

	if err := os.MkdirAll(resolverDir, 0o755); err != nil {
		return fmt.Errorf("create resolver directory: %w", err)
	}

	content := fmt.Sprintf("%s\nnameserver 127.0.0.1\nport %d\n", resolverMarker, port)
	created := make([]string, 0)

	for _, name := range p.resolverFileNames() {
		path := filepath.Join(resolverDir, name)
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			for _, done := range created {
				_ = os.Remove(filepath.Join(resolverDir, done))
			}
			return fmt.Errorf("write resolver for %s: %w", name, err)
		}
		created = append(created, name)
	}

	p.resolvers = created
	log.Printf("✓ Installed %d system resolver(s) pointing at 127.0.0.1:%d", len(created), port)
	return nil
}

func (p *DNSProxy) cleanupSystemResolvers() {
	if len(p.resolvers) == 0 {
		return
	}

	for _, name := range p.resolvers {
		if err := os.Remove(filepath.Join(resolverDir, name)); err != nil && !os.IsNotExist(err) {
			log.Printf("⚠️ Failed to remove resolver for %s: %v", name, err)
		}
	}
	log.Printf("✓ Removed %d system resolver(s)", len(p.resolvers))
	p.resolvers = nil
}

// ReconcileResolvers removes resolver files this product generated but did not
// clean up, for instance after SIGKILL. Such a file names a port that is not
// being served, which stops the affected domains from resolving at all.
func ReconcileResolvers() error {
	entries, err := os.ReadDir(resolverDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}

	removed := 0
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		path := filepath.Join(resolverDir, entry.Name())
		payload, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		if !strings.Contains(string(payload), resolverMarker) {
			continue
		}
		if err := os.Remove(path); err != nil {
			log.Printf("⚠️ Could not remove orphaned resolver %s: %v", entry.Name(), err)
			continue
		}
		removed++
	}

	if removed > 0 {
		log.Printf("Removed %d orphaned resolver file(s) from a previous run", removed)
	}
	return nil
}

// isIPv6Preferring reports query types that let a client reach a host without
// using the A records the applier installs routes for. AAAA is the obvious one;
// HTTPS and SVCB carry address hints that clients connect to directly.
func isIPv6Preferring(qtype uint16) bool {
	switch qtype {
	case dns.TypeAAAA, dns.TypeHTTPS, dns.TypeSVCB:
		return true
	default:
		return false
	}
}

func (p *DNSProxy) handleDNSRequest(w dns.ResponseWriter, r *dns.Msg) {
	if len(r.Question) == 0 {
		reply := new(dns.Msg)
		reply.SetRcode(r, dns.RcodeFormatError)
		_ = w.WriteMsg(reply)
		return
	}

	question := r.Question[0]
	domain := strings.TrimSuffix(strings.ToLower(question.Name), ".")

	if p.config.ForceIPv4Enabled() && isIPv6Preferring(question.Qtype) {
		// Empty NOERROR steers the client to the A record, which is the address
		// family the tethered route actually covers.
		reply := new(dns.Msg)
		reply.SetReply(r)
		reply.Authoritative = false
		_ = w.WriteMsg(reply)
		return
	}

	if cached, ok := p.cache.Get(r); ok {
		_ = w.WriteMsg(cached)
		return
	}

	reply, routable, err := p.upstream.Resolve(r)
	if err != nil {
		log.Printf("⚠️ Resolution failed for %s (%s): %v", domain, dns.TypeToString[question.Qtype], err)
		dns.HandleFailed(w, r)
		return
	}

	if routable && p.applier != nil {
		p.applier.Submit(answerIPv4(reply))
	}

	p.cache.Put(r, reply)
	_ = w.WriteMsg(reply)
}

func answerIPv4(msg *dns.Msg) []string {
	var hosts []string
	for _, rr := range msg.Answer {
		if a, ok := rr.(*dns.A); ok && a.A != nil {
			hosts = append(hosts, a.A.String())
		}
	}
	return hosts
}
